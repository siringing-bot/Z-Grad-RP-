-- Сеть — отправляем whitelist клиентам
util.AddNetworkString("ZGrad_PropWhitelist")
util.AddNetworkString("ZGrad_PropWhitelist_Request")

local function SendWhitelist(ply)
    if not IsValid(ply) then return end
    
    local propList = {}
    for model, allowed in pairs(ZGrad_AllowedProps) do
        if allowed then
            table.insert(propList, model)
        end
    end

    net.Start("ZGrad_PropWhitelist")
    net.WriteUInt(#propList, 16)
    for _, model in ipairs(propList) do
        net.WriteString(model)
    end
    net.Send(ply)
end

hook.Add("PlayerInitialSpawn", "ZGrad_SendPropWhitelist", function(ply)
    -- Уменьшаем задержку до 1 секунды для более быстрой загрузки
    timer.Simple(1, function()
        SendWhitelist(ply)
    end)
end)

-- Позволяем клиенту запросить вайтлист, если он не пришел
net.Receive("ZGrad_PropWhitelist_Request", function(len, ply)
    SendWhitelist(ply)
end)

-- Команда для принудительного обновления у всех
concommand.Add("zgrad_propwhitelist_sync", function(ply, cmd, args)
    if IsValid(ply) and not ply:IsSuperAdmin() then return end
    
    for _, v in ipairs(player.GetAll()) do
        SendWhitelist(v)
    end
    
    if IsValid(ply) then
        DarkRP.notify(ply, 0, 4, "Вайтлист пропов синхронизирован для всех игроков!")
    else
        print("[Z-Grad RP] Prop whitelist synced for all players")
    end
end)


-- Блокируем спаун запрещённых пропов
hook.Add("PlayerSpawnProp", "ZGrad_PropWhitelistCheck", function(ply, model)
    -- Админы могут спаунить всё
    if ply:IsSuperAdmin() then return true end

    local cleanModel = string.lower(string.Trim(model))

    for allowedModel, _ in pairs(ZGrad_AllowedProps) do
        if string.lower(allowedModel) == cleanModel then
            return true
        end
    end

    DarkRP.notify(ply, 1, 4, "Этот проп не разрешён на сервере Z-Grad RP!")
    return false
end)

-- Авто-зафриз при спауне
hook.Add("PlayerSpawnedProp", "ZGrad_FreezeOnSpawn", function(ply, model, ent)
    if IsValid(ent) then
        local phys = ent:GetPhysicsObject()
        if IsValid(phys) then
            phys:EnableMotion(false)
            phys:Sleep()
        end
    end
end)

-- Прозрачность при взятии физганом
hook.Add("PhysgunPickup", "ZGrad_PhysgunTransparencyStart", function(ply, ent)
    if IsValid(ent) and ent:GetClass() == "prop_physics" then
        ent:SetRenderMode(RENDERMODE_TRANSALPHA)
        local col = ent:GetColor()
        ent:SetColor(Color(col.r, col.g, col.b, 150))
        
        -- Делаем проп призрачным (проходит сквозь игроков и другие пропы)
        ent:SetCollisionGroup(COLLISION_GROUP_WORLD)
    end
end)

-- Возврат непрозрачности и авто-зафриз при отпускании физгана
hook.Add("PhysgunDrop", "ZGrad_PhysgunTransparencyEnd", function(ply, ent)
    if IsValid(ent) and ent:GetClass() == "prop_physics" then
        ent:SetRenderMode(RENDERMODE_NORMAL)
        local col = ent:GetColor()
        ent:SetColor(Color(col.r, col.g, col.b, 255))
        
        -- Возвращаем коллизию
        ent:SetCollisionGroup(COLLISION_GROUP_NONE)
        
        -- Замораживаем проп после того как его отпустили
        local phys = ent:GetPhysicsObject()
        if IsValid(phys) then
            phys:EnableMotion(false)
            phys:Sleep()
        end
    end
end)

